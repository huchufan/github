"""
Memory Framework - Layers Module (compat shim + Layers PoC)
Provides MemoryLayer base, ImmediateContextMemory, SemanticMemory, Session/Episodic/Archive stubs,
LRUCache import and Layers PoC used by autogenerated tests.
"""
from __future__ import annotations
from datetime import datetime, timedelta, timezone
from typing import Any, Dict, List, Optional
from .lru import LRUCache
from .layers_types import KnowledgeItem, SessionRecord

class MemoryLayer:
    """Base memory layer interface"""
    def __init__(self, name: str, ttl: Optional[timedelta] = None):
        self.name = name
        self.ttl = ttl
        self.storage: Dict[str, Any] = {}
        self.created_at: Dict[str, datetime] = {}

    def now(self) -> datetime:
        return datetime.now(timezone.utc)

    def store(self, key: str, value: Any) -> None:
        self.storage[key] = value
        self.created_at[key] = self.now()

    def retrieve(self, key: str) -> Optional[Any]:
        if key not in self.storage:
            return None
        created = self.created_at.get(key)
        if self.ttl and created is not None:
            # guard against naive datetimes set by tests or external code
            try:
                if created.tzinfo is None:
                    from datetime import timezone
                    created = created.replace(tzinfo=timezone.utc)
            except Exception:
                pass
            if (self.now() - created) > self.ttl:
                del self.storage[key]
                del self.created_at[key]
                return None
        return self.storage[key]

    def search(self, query: str, limit: int = 10) -> List[Any]:
        results: List[Any] = []
        for k, v in self.storage.items():
            if query.lower() in str(v).lower():
                results.append(v)
                if len(results) >= limit:
                    break
        return results

class ImmediateContextMemory(MemoryLayer):
    def __init__(self, max_size: Optional[int] = None, **kwargs):
        # Accept max_size for compatibility with tests; unused in PoC but stored.
        super().__init__("immediate", ttl=timedelta(hours=2))
        self.max_size = max_size or 1024
        # conversation turns storage (list of dict-like entries)
        self.turns: List[Dict[str, Any]] = []
        # execution state store
        self.execution_state: Dict[str, Any] = {}
        # attention stack
        self.attention_stack: List[Any] = []

    def record_conversation_turn(self, user_message: str, agent_response: str) -> Dict[str, Any]:
        t = {
            'timestamp': self.now(),
            'user_message': user_message,
            'agent_response': agent_response,
        }
        self.turns.append(t)
        # trim to max_size for conversation history
        if len(self.turns) > self.max_size:
            self.turns = self.turns[-self.max_size:]
        return t

    def get_conversation_context(self, window_size: int = 5) -> Any:
        # return a simple context object with required attributes
        window = self.turns[-window_size:]
        ctx = type('Ctx', (), {})()
        ctx.conversation_state = 'active' if window else 'idle'
        ctx.last_turn_time = window[-1]['timestamp'] if window else None
        return ctx

    def update_execution_state(self, new_state: Dict[str, Any]) -> None:
        self.execution_state.update(new_state)

    def get_attention_context(self) -> Any:
        ac = type('AC', (), {})()
        ac.primary = self.attention_stack[0] if self.attention_stack else None
        ac.secondary = self.attention_stack[1:] if len(self.attention_stack) > 1 else []
        ac.focus_strength = (1.0 / len(self.attention_stack)) if self.attention_stack else 0.0
        return ac

class SemanticMemory(MemoryLayer):
    """Stub semantic memory for embeddings-backed storage (mocked for tests)
    Provides index and query semantics but stores plain values for PoC.
    """
    def __init__(self, dim: int = 128):
        super().__init__("semantic", ttl=None)
        # simple list index
        self.index: List[Dict[str, Any]] = []
        self.dim = dim

    def index_item(self, id: str, vector: List[float], payload: Any):
        self.index.append({"id": id, "vector": vector, "payload": payload})

    def store_knowledge_item(self, item: KnowledgeItem):
        # assign id if missing
        if not getattr(item, 'knowledge_id', None):
            item.knowledge_id = f"k_{len(self.index)+1}"
        self.index.append({"id": item.knowledge_id, "payload": item})
        self.storage[item.knowledge_id] = item
        return item

    def semantic_search(self, query: str, top_k: int = 5) -> List[KnowledgeItem]:
        # PoC: return items whose content contains query
        res = []
        for e in self.index:
            payload = e.get('payload')
            if isinstance(payload, KnowledgeItem) and query.lower() in payload.content.lower():
                res.append(payload)
                if len(res) >= top_k:
                    break
        return res

    def build_knowledge_graph(self):
        # PoC: return dict of id->concepts
        return {e['id']: getattr(e.get('payload'), 'concepts', []) for e in self.index}

class SessionMemory(MemoryLayer):
    """Minimal session-scoped memory (episodic short-lived between requests)
    Async/sync interfaces not required for PoC: simple wrapper around MemoryLayer.
    """
    def __init__(self):
        super().__init__("session", ttl=timedelta(hours=1))

class EpisodicMemory(MemoryLayer):
    """Episodic memory across a conversation/session with longer TTL."""
    def __init__(self):
        super().__init__("episodic", ttl=timedelta(days=1))

class ArchiveMemory(MemoryLayer):
    """Archive storage (cold) - readonly PoC interface."""
    def __init__(self):
        super().__init__("archive", ttl=None)

    def archive_item(self, key: str, value: Any):
        # append-only behavior
        self.storage[key] = value

    def archive_session(self, session: SessionRecord):
        aid = f"arc_{len(self.storage)+1}"
        self.storage[aid] = session
        class Ref:
            def __init__(self, archive_id):
                self.archive_id = archive_id
        return Ref(archive_id=aid)

    def retrieve_archived_session(self, archive_id: str) -> Optional[SessionRecord]:
        return self.storage.get(archive_id)

