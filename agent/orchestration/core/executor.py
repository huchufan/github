class ErrorHandlingStrategy:
    def __init__(self, skill_registry: Optional[Dict[str, Any]] = None, default_strategy: str = 'retry_on_transient'):
        self.skill_registry = skill_registry or {}
        self.default_strategy = default_strategy
        # strategies mapping for tests to mutate directly
        # example keys: 'retry_on_transient', 'execute_fallback', 'skip_and_continue', 'immediate_fail', 'no_retry'
        self.strategies: Dict[str, Dict[str, Any]] = {
            'retry_on_transient': {'action': 'RETRY', 'retries': 3},
            'execute_fallback': {'action': 'FALLBACK', 'retries': 1, 'fallback_skill': 'alternative_skill'},
            'skip_and_continue': {'action': 'CONTINUE', 'retries': 0},
            'immediate_fail': {'action': 'STOP', 'retries': 0},
            'no_retry': {'action': 'RETRY', 'retries': 0},
        }

    def categorize_error(self, err: Exception) -> str:
        # PoC categorization
        if isinstance(err, TimeoutError) or isinstance(err, asyncio.TimeoutError):
            return 'TIMEOUT'
        # handle test-local RateLimitError classes (by name) or the shared one
        if isinstance(err, RateLimitError) or getattr(getattr(err, '__class__', None), '__name__', '') == 'RateLimitError':
            return 'NETWORK_ERROR'
        try:
            from agent.core.errors import ConnectionError
            if isinstance(err, ConnectionError):
                return 'TRANSIENT'
        except Exception:
            pass
        return 'GENERIC_ERROR'

    def get_recovery_action(self, strategy: Dict[str, Any]):
        # strategy is a dict containing action and params
        # return a dataclass-like object with attribute access expected by tests
        try:
            from agent.core.types import RecoveryAction
            action = strategy.get('action') if isinstance(strategy, dict) else getattr(strategy, 'action', None)
            fallback = strategy.get('fallback_skill') if isinstance(strategy, dict) else getattr(strategy, 'fallback_skill', None)
            return RecoveryAction(action=action or 'STOP', fallback_skill=fallback)
        except Exception:
            # fallback: return a simple object
            class RA:
                def __init__(self, d):
                    self.action = d.get('action') if isinstance(d, dict) else getattr(d, 'action', None)
                    self.fallback_skill = d.get('fallback_skill') if isinstance(d, dict) else getattr(d, 'fallback_skill', None)
            return RA(strategy)

    def select_recovery_strategy(self, task: Any = None, err_type: str = '', retry_count: int = 0, default_strategy: Optional[str] = None) -> Dict[str, Any]:
        """Select a recovery strategy for a given task and error type.
        Prioritize explicit strategy from task.retry_policy if present in self.strategies; otherwise fallback to default heuristics.
        """
        # if task defines explicit retry_policy and it's registered, use it
        policy = None
        try:
            policy = getattr(task, 'retry_policy', None)
        except Exception:
            policy = None
        if policy and policy in self.strategies:
            strat = dict(self.strategies[policy])
            # attach current retry_count
            strat['retries_done'] = retry_count
            return strat

        strategy = default_strategy or self.default_strategy
        # fallback heuristics
        if strategy == 'retry_on_transient' and retry_count >= 3:
            return {'action': 'STOP'}
        if err_type == 'TIMEOUT':
            return {'action': 'RETRY'}
        if err_type == 'NETWORK_ERROR':
            return {'action': 'FALLBACK', 'fallback_skill': 'alternative_skill'}
        return {'action': 'STOP'}

import asyncio
from typing import Any, Dict, Optional, List
from agent.core.types import ExecutionResult, TaskResult, SubTask

class OrchestrationEngine:
    def __init__(self, skill_registry: Optional[Dict[str, Any]] = None, error_strategy: Optional[object] = None):
        # skill_registry: name -> callable (sync or async)
        self.skill_registry = skill_registry or {}
        self.error_strategy = error_strategy or ErrorHandlingStrategy()
        self.state: Dict[str, Any] = {}

    async def _run_single(self, subtask: SubTask, context: Dict[str, Any]) -> TaskResult:
        skill = self.skill_registry.get(subtask.skill_name)
        if skill is None:
            return TaskResult(task_id=subtask.id, status='FAILURE', error=f"skill {subtask.skill_name} not found", success=False)
        attempts = 0
        max_retries = getattr(subtask, 'retry_policy', 1) if isinstance(subtask, SubTask) else 1
        while True:
            try:
                # call sync or async
                if asyncio.iscoroutinefunction(skill):
                    res = await skill(subtask.parameters, context)
                else:
                    res = skill(subtask.parameters, context)
                    if asyncio.iscoroutine(res):
                        res = await res
                return TaskResult(task_id=subtask.id, status='SUCCESS', result=res, success=True)
            except Exception as e:
                attempts += 1
                err_type = self.error_strategy.categorize_error(e)
                strat = self.error_strategy.select_recovery_strategy(task=subtask, err_type=err_type, retry_count=attempts)
                action = strat.get('action') if isinstance(strat, dict) else getattr(strat, 'action', 'STOP')
                if action == 'RETRY' and attempts <= max_retries:
                    await asyncio.sleep(0)  # yield
                    continue
                if action == 'FALLBACK':
                    fb = strat.get('fallback_skill') if isinstance(strat, dict) else getattr(strat, 'fallback_skill', None)
                    if fb and fb in self.skill_registry:
                        try:
                            fb_skill = self.skill_registry[fb]
                            if asyncio.iscoroutinefunction(fb_skill):
                                fres = await fb_skill(subtask.parameters, context)
                            else:
                                fres = fb_skill(subtask.parameters, context)
                                if asyncio.iscoroutine(fres):
                                    fres = await fres
                            return TaskResult(task_id=subtask.id, status='SUCCESS', result=fres, success=True)
                        except Exception as e2:
                            return TaskResult(task_id=subtask.id, status='FAILURE', error=str(e2), success=False)
                # otherwise stop
                return TaskResult(task_id=subtask.id, status='FAILURE', error=str(e), success=False)

    async def orchestrate_execution(self, plan: 'ExecutionPlan') -> ExecutionResult:
        # simple level-by-level executor
        result = ExecutionResult(status='SUCCESS', tasks_executed=0, tasks_completed=0, tasks_failed=0)
        context = {}
        for level in getattr(plan, 'execution_order', []) or []:
            # run level tasks in parallel
            tasks: List[Any] = []
            for st in level:
                tasks.append(self._run_single(st, context))
            completed: List[TaskResult] = await asyncio.gather(*tasks)
            for tr in completed:
                result.tasks_executed += 1
                if tr.success:
                    result.tasks_completed += 1
                else:
                    result.tasks_failed += 1
                    result.status = 'FAILURE'
            if result.status == 'FAILURE':
                # stop on first failed level for PoC
                break
        return result

